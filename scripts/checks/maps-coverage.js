#!/usr/bin/env node
"use strict";

/**
 * /maps:coverage — the maps suite's SELF-INVENTORY enforcer.
 *
 * The direct analog of /scan:scan-coverage, for the /maps:* suite. The maps
 * registry (/maps:all), the /maps:<x> skills, and the on-disk map files drift:
 * a new /maps:<x> skill or a new generated map file lands but /maps:all never
 * lists it, so coverage/staleness silently rots — the same dir<->aggregator
 * drift class scan-coverage closes for scans.
 *
 * REJECTS (exit 1) on any finding:
 *   1. UNREGISTERED-SKILL — a /maps:<x> skill exists but /maps:all does not
 *      reference it (and it is not on the allowlist).
 *   2. DANGLING-REGISTRY  — /maps:all references /maps:<x> but no skill file exists.
 *   3. ORPHAN-MAP-FILE    — a generated map file in .claude/project/maps/ has no
 *      matching /maps:<x> generator AND is not on the allowlist (manual registries
 *      / inventory snapshots / spec graphs are allowlisted with a reason).
 *   4. STALE-EXCLUSION / REASONLESS-EXCLUSION — allowlist hygiene (mirrors scan-coverage).
 * Plus a non-blocking WARN: generated map files older than STALE_DAYS (default 7).
 * Internal/setup error => exit 2 (fail-closed: a self-inventory that errors must
 * never read green).
 *
 * Pure core = evaluate({ mapsSkills, allSelf, allReferenced, mapFiles, generators,
 *   allowlist, staleNames }) with injected seams so the bite-test proves each class.
 * Mirrors scripts/checks/scan-coverage.js.
 *
 *   node scripts/checks/maps-coverage.js [--json] [--stale-days N]
 */

const fs = require("fs");
const path = require("path");

const ROOT = process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, "..", "..");
const NAME = "maps-coverage";

const MAPS_SKILL_DIR = path.join(ROOT, ".claude", "commands", "maps");
const MAPS_DATA_DIR = path.join(ROOT, ".claude", "project", "maps");
const ALL_MD = path.join(MAPS_SKILL_DIR, "all.md");
const ALLOWLIST = path.join(__dirname, "maps-coverage.allowlist.json");
const STALE_DAYS_DEFAULT = 7;

// /maps:<x> skills (basenames sans .md). 'all' is the aggregator; 'coverage' is
// this enforcer — neither needs to be "registered by all" the way generators do,
// but both are listed in all.md anyway; the self/allowlist handling covers them.
function listMapsSkills(dir) {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .map((f) => f.slice(0, -3));
}

// /maps:<x> tokens referenced anywhere in all.md (registry tables, refresh list).
function parseAllRefs(md) {
  const set = new Set();
  for (const m of md.matchAll(/\/maps:([a-z0-9][a-z0-9-]*)/gi)) set.add(m[1].toLowerCase());
  return set;
}

// Generated map files in the data dir, keyed to their generator basename.
// A file `hooks.jsonl` / `hooks.md` is generated by /maps:hooks. We derive the
// generator stem from the filename stem (before the first '.').
function listMapFiles(dir) {
  let ents;
  try {
    ents = fs.readdirSync(dir);
  } catch {
    return [];
  }
  return ents.filter((f) => !f.startsWith(".") && /\.(jsonl|md|json)$/.test(f));
}

/**
 * Pure assertion core. Returns findings[] (empty = maps suite is self-consistent).
 * @param mapsSkills    string[] of /maps:<x> skill basenames (incl. "all")
 * @param allSelf       the aggregator's own name ("all")
 * @param allReferenced Set<string> of /maps:<x> names referenced by all.md
 * @param mapFiles      string[] of filenames in the maps data dir
 * @param generators    Set<string> of skill basenames that GENERATE a persisted map
 * @param allowlist     { [name]: reason } — map-file stems / skills intentionally exempt
 * @param staleNames    string[] of generated map files flagged stale (mtime > threshold)
 */
function evaluate({ mapsSkills, allSelf, allReferenced, mapFiles, generators, allowlist, staleNames }) {
  const findings = [];
  const skillSet = new Set(mapsSkills);
  const excl = allowlist || {};
  const exclSet = new Set(Object.keys(excl));

  // 1. UNREGISTERED-SKILL — every /maps:<x> skill is referenced by /maps:all or excluded.
  for (const s of mapsSkills) {
    if (s === allSelf) continue;
    if (allReferenced.has(s)) continue;
    if (exclSet.has(s)) continue;
    findings.push({
      severity: "high",
      check: NAME,
      kind: "unregistered-skill",
      message: `/maps:${s} exists but /maps:all does not reference it and it is not on the allowlist`,
      file: `.claude/commands/maps/${s}.md`,
      suggestedFix: `Add /maps:${s} to /maps:all's registry, OR add it to maps-coverage.allowlist.json with a reason.`,
    });
  }

  // 2. DANGLING-REGISTRY — /maps:all references a skill with no file.
  for (const r of allReferenced) {
    if (r === allSelf) continue;
    if (!skillSet.has(r)) {
      findings.push({
        severity: "high",
        check: NAME,
        kind: "dangling-registry",
        message: `/maps:all references /maps:${r} but no .claude/commands/maps/${r}.md exists`,
        suggestedFix: `Remove the stale /maps:${r} reference from all.md, or restore the skill.`,
      });
    }
  }

  // 3. ORPHAN-MAP-FILE — a persisted map file with no generator skill + not allowlisted.
  for (const f of mapFiles) {
    const stem = f.split(".")[0].toLowerCase(); // hooks.jsonl -> hooks
    if (generators.has(stem)) continue;
    if (exclSet.has(stem) || exclSet.has(f)) continue;
    findings.push({
      severity: "medium",
      check: NAME,
      kind: "orphan-map-file",
      message: `map file ${f} has no /maps:<x> generator and is not on the allowlist`,
      file: `.claude/project/maps/${f}`,
      suggestedFix: `Either add a /maps:${stem} generator, or allowlist "${stem}" in maps-coverage.allowlist.json with a reason (e.g. manual registry / inventory snapshot).`,
    });
  }

  // 4. allowlist hygiene
  for (const [name, reason] of Object.entries(excl)) {
    const known = skillSet.has(name) || mapFiles.some((f) => f.split(".")[0].toLowerCase() === name || f === name);
    if (!known) {
      findings.push({
        severity: "low",
        check: NAME,
        kind: "stale-exclusion",
        message: `maps-coverage.allowlist.json excludes "${name}" but no such skill or map file exists`,
        suggestedFix: `Remove the stale exclusion.`,
      });
    } else if (!reason || !String(reason).trim()) {
      findings.push({
        severity: "low",
        check: NAME,
        kind: "reasonless-exclusion",
        message: `"${name}" is excluded without a reason`,
        suggestedFix: `Add a reason string.`,
      });
    }
  }

  // 5. WARN (non-blocking): stale generated maps.
  for (const s of staleNames || []) {
    findings.push({
      severity: "warn",
      check: NAME,
      kind: "stale-map",
      message: `generated map ${s} is stale (older than threshold)`,
      suggestedFix: `Refresh it: /maps:${s.split(".")[0]} --refresh (or /maps:all --regenerate).`,
    });
  }

  return findings;
}

function loadAllowlist() {
  if (!fs.existsSync(ALLOWLIST)) return {};
  const raw = JSON.parse(fs.readFileSync(ALLOWLIST, "utf8").replace(/^﻿/, ""));
  const map = raw && raw.exclusions ? raw.exclusions : raw;
  const out = {};
  for (const [k, v] of Object.entries(map || {})) {
    if (k.startsWith("_")) continue;
    out[k.toLowerCase()] = v; // case-insensitive match (map-file stems vary case, e.g. INVENTORY.md)
  }
  return out;
}

function main() {
  const asJson = process.argv.includes("--json");
  const sdIdx = process.argv.indexOf("--stale-days");
  const staleDays = sdIdx !== -1 ? Number(process.argv[sdIdx + 1]) : STALE_DAYS_DEFAULT;

  let mapsSkills, allReferenced, mapFiles, allowlist, staleNames;
  try {
    mapsSkills = listMapsSkills(MAPS_SKILL_DIR);
    allReferenced = parseAllRefs(fs.readFileSync(ALL_MD, "utf8"));
    mapFiles = listMapFiles(MAPS_DATA_DIR);
    allowlist = loadAllowlist();
    // Generators = the skills that produce a persisted map (every /maps:<x> skill
    // whose stem matches a persisted file, plus the known generators). Conservative:
    // treat every maps skill (except all/coverage) as a potential generator stem.
    const cutoff = Date.now() - staleDays * 86400000;
    staleNames = mapFiles.filter((f) => {
      if (!/\.(jsonl|md)$/.test(f)) return false;
      try {
        return fs.statSync(path.join(MAPS_DATA_DIR, f)).mtimeMs < cutoff;
      } catch {
        return false;
      }
    });
  } catch (e) {
    const msg = String((e && e.message) || e);
    process.stdout.write(
      (asJson ? JSON.stringify({ ok: false, check: NAME, error: msg }) : `ERROR  ${NAME}: ${msg}`) + "\n",
    );
    process.exit(2);
  }

  const generators = new Set(mapsSkills.filter((s) => s !== "all" && s !== "coverage"));
  const findings = evaluate({
    mapsSkills,
    allSelf: "all",
    allReferenced,
    mapFiles,
    generators,
    allowlist,
    staleNames,
  });

  const blocking = findings.filter((f) => f.severity !== "warn");
  if (asJson) {
    process.stdout.write(
      JSON.stringify(
        {
          ok: blocking.length === 0,
          check: NAME,
          counts: { skills: mapsSkills.length, mapFiles: mapFiles.length, excluded: Object.keys(allowlist).length, stale: staleNames.length },
          findings,
        },
        null,
        2,
      ) + "\n",
    );
  } else {
    for (const f of findings) {
      const tag = f.severity === "warn" ? "WARN" : f.severity === "high" ? "FAIL" : "WARN";
      process.stdout.write(`${tag}  [${f.kind}] ${f.message}\n`);
    }
    process.stdout.write(
      `# maps-coverage: ${mapsSkills.length} skills, ${mapFiles.length} map files, ${Object.keys(allowlist).length} excluded, ${staleNames.length} stale — ${blocking.length} blocking finding(s)\n`,
    );
  }
  process.exit(blocking.length ? 1 : 0);
}

if (require.main === module) main();

module.exports = { evaluate, parseAllRefs, listMapsSkills };
